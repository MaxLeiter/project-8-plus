#!/usr/bin/env python3
"""Compile qb/cas_preview.q (P8Plus's own QB code) into src/p8plus_caspreview_qb.h.

    python native/p8plus_plugin/tools/gen_caspreview.py [--check]

Uses thp8-mod tools/qbc (qbtext.compile_qb). The header holds only our bytecode and checksums of names;
the plugin (p8plus_caspreview.c) writes it into the game's symbol table at run time. Scripts named after a
game script (WRAPS) are wrappers: the plugin keeps the game's body as p8p_orig_<name>. Every other script
must be called p8p_*, and no p8p_* checksum may be the checksum of a game name (tools/qbkeys.json).
--check: fail if the committed header differs from a fresh build (CI / pre-commit).
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLUGIN = HERE.parent
REPO = PLUGIN.parent.parent
sys.path.insert(0, str(REPO / 'tools' / 'qbc'))
import qbtext as QT  # noqa: E402
from nscrc import qbkey  # noqa: E402

SRC = PLUGIN / 'qb' / 'cas_preview.q'
OUT = PLUGIN / 'src' / 'p8plus_caspreview_qb.h'
FILE_ID_NAME = 'scripts\\p8plus\\cas_preview'
CAS_FILE_ID = 0xA11C8D25      # #fileid of the game's CAS script file (pak/CAS_common, cas_common_scripts.qb)
WRAPS = ['edit_skater_highlight_cas_item', 'edit_skater_set_selected_cas_item', 'cas_add_item',
         'edit_skater_keep_part_prompt']
GLOBALS = ['p8p_cas_preview_frames', 'p8p_cas_preview_refreshing']   # defined by the plugin (int / int)


def c_bytes(b, indent='    '):
    lines = []
    for i in range(0, len(b), 16):
        lines.append(indent + ', '.join(f'0x{x:02X}' for x in b[i:i + 16]) + ',')
    return '\n'.join(lines)


def build():
    text = SRC.read_text(encoding='utf-8')
    names = {}
    for m in re.finditer(r'(?m)^script\s+([A-Za-z_][A-Za-z0-9_]*)', text):
        names[qbkey(m.group(1))] = m.group(1)
    fid = qbkey(FILE_ID_NAME)
    q = QT.compile_qb(text, compress=False, fileid=fid)
    try:
        known = {int(k, 16): v for k, v in json.loads((REPO / 'tools' / 'qbkeys.json').read_text()).items()}
    except (OSError, ValueError):
        known = {}
    wraps, helpers = [], []
    for s in q.sections:
        nm = names.get(s.key)
        if nm is None:
            raise SystemExit(f'section {s.key:08x}: not a script of {SRC.name}')
        code = s.value.code
        if nm in WRAPS:
            alias = 'p8p_orig_' + nm
            if qbkey(alias).to_bytes(4, 'little') not in code:
                raise SystemExit(f'wrapper {nm} does not call {alias}')
            wraps.append((nm, alias, s.value.crc, code))
        else:
            if not nm.startswith('p8p_'):
                raise SystemExit(f'{nm}: helper scripts must be named p8p_*')
            helpers.append((nm, s.value.crc, code))
    for nm in [h[0] for h in helpers] + [w[1] for w in wraps] + GLOBALS:
        kn = known.get(qbkey(nm))
        if kn is not None and kn.lower() != nm.lower():
            raise SystemExit(f'{nm}: checksum {qbkey(nm):08x} is the game name {kn}')
        if kn is not None:
            raise SystemExit(f'{nm}: already a game name')
    missing = [w for w in WRAPS if w not in [x[0] for x in wraps]]
    if missing:
        raise SystemExit(f'wrappers missing: {missing}')

    o = []
    o.append('/* GENERATED by tools/gen_caspreview.py from qb/cas_preview.q -- do not edit. */')
    o.append('/* P8Plus\'s own QB bytecode (qbc syntax compiled by thp8-mod tools/qbc); no game code. */')
    o.append('#ifndef P8PLUS_CASPREVIEW_QB_H')
    o.append('#define P8PLUS_CASPREVIEW_QB_H')
    o.append('#include <stdint.h>')
    o.append('')
    o.append(f'#define P8P_QB_FILE_ID   0x{fid:08X}u   /* qbkey("{FILE_ID_NAME.replace(chr(92), chr(92) * 2)}") */')
    o.append(f'#define P8P_CAS_FILE_ID  0x{CAS_FILE_ID:08X}u   /* the game\'s CAS script file */')
    o.append(f'#define P8P_KEY_FRAMES   0x{qbkey(GLOBALS[0]):08X}u   /* {GLOBALS[0]} (int) */')
    o.append(f'#define P8P_KEY_REFRESHING 0x{qbkey(GLOBALS[1]):08X}u /* {GLOBALS[1]} (int) */')
    o.append('')
    o.append('typedef struct p8p_qb_script {')
    o.append('    const char*    name;')
    o.append('    uint32_t       key;')
    o.append('    const char*    alias;      /* wrappers: the game body is kept under this name; NULL for helpers */')
    o.append('    uint32_t       alias_key;')
    o.append('    uint32_t       crc;        /* qbc script crc of the bytecode */')
    o.append('    uint32_t       len;')
    o.append('    const uint8_t* code;       /* raw bytecode, stored uncompressed (ulen == clen) */')
    o.append('} p8p_qb_script;')
    o.append('')
    for nm, crc, code in helpers:
        o.append(f'static const uint8_t p8p_bc_{nm}[{len(code)}] = {{')
        o.append(c_bytes(code))
        o.append('};')
    for nm, alias, crc, code in wraps:
        o.append(f'static const uint8_t p8p_bc_{nm}[{len(code)}] = {{')
        o.append(c_bytes(code))
        o.append('};')
    o.append('')
    o.append('static const p8p_qb_script p8p_qb_helpers[] = {')
    for nm, crc, code in helpers:
        o.append(f'    {{ "{nm}", 0x{qbkey(nm):08X}u, 0, 0, 0x{crc:08X}u, {len(code)}u, p8p_bc_{nm} }},')
    o.append('};')
    o.append('static const p8p_qb_script p8p_qb_wraps[] = {')
    for nm, alias, crc, code in wraps:
        o.append(f'    {{ "{nm}", 0x{qbkey(nm):08X}u, "{alias}", 0x{qbkey(alias):08X}u, 0x{crc:08X}u, '
                 f'{len(code)}u, p8p_bc_{nm} }},')
    o.append('};')
    o.append('#define P8P_N_HELPERS ((int)(sizeof p8p_qb_helpers / sizeof p8p_qb_helpers[0]))')
    o.append('#define P8P_N_WRAPS   ((int)(sizeof p8p_qb_wraps / sizeof p8p_qb_wraps[0]))')
    o.append('')
    o.append('#endif /* P8PLUS_CASPREVIEW_QB_H */')
    return '\n'.join(o) + '\n', helpers, wraps


def main():
    hdr, helpers, wraps = build()
    if '--check' in sys.argv:
        cur = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if cur != hdr:
            raise SystemExit(f'{OUT.name} is out of date: run tools/gen_caspreview.py')
        print(f'{OUT.name} up to date')
        return
    OUT.write_text(hdr, encoding='utf-8', newline='\n')
    print(f'{OUT.name}: {len(helpers)} helpers, {len(wraps)} wrappers, '
          f'{sum(len(h[2]) for h in helpers) + sum(len(w[3]) for w in wraps)} B bytecode')


if __name__ == '__main__':
    main()
