"""Generates the demo script mods (unified diffs) in work/qbc/mods/scripts/ from the user's own game files.

  10_cutscene_render_unlock.diff   CutsceneSetup (scripts\\game\\cutscene.qb, 7b9ec42b) no longer forces
                                   render_lock_framerate = 2 (game_lock_framerate = 2 is kept)
  20_fmv_bg_render_unlock.diff     pause_menu_fmv_play, ui_map_fmv_play, ThrowUpObserverBG no longer force
                                   render_lock_framerate = 2 (their save/restore of the old value stays: harmless)
Also writes an example full-section replacement mod to work/qbc/mods/examples/ (not applied by default).
Usage: make_demo_mods.py [--game DIR]
"""
import difflib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pakfile  # noqa: E402
import qbfile as Q  # noqa: E402
import qbtext  # noqa: E402
from gamepaths import data_dir, MAIN_HDR, MAIN_DATA, WORK  # noqa: E402
from qbnames import qb_label  # noqa: E402

EDITS = {
    '10_cutscene_render_unlock.diff': [(0x7b9ec42b, ['CutsceneSetup'])],
    '20_fmv_bg_render_unlock.diff': [(0x92b266a5, ['pause_menu_fmv_play']),
                                     (0x32f30e5f, ['ui_map_fmv_play']),
                                     (0x094cc35d, ['ThrowUpObserverBG'])],
}
LOCK_LINE = re.compile(r'^\s*change render_lock_framerate = 2\s*$')


def drop_lock(text, scripts):
    out = []
    cur = None
    hits = []
    for ln in text.split('\n'):
        m = re.match(r'^script (\S+)', ln)
        if m:
            cur = m.group(1)
        elif ln.startswith('endscript'):
            cur = None
        if cur in scripts and LOCK_LINE.match(ln):
            hits.append(cur)
            continue
        out.append(ln)
    if sorted(hits) != sorted(scripts):
        raise SystemExit(f'expected one lock line in each of {scripts}, found {hits}')
    return '\n'.join(out)


def main():
    game = sys.argv[sys.argv.index('--game') + 1] if '--game' in sys.argv else None
    data = data_dir(game)
    p = pakfile.load(data / MAIN_HDR, data / MAIN_DATA)
    outdir = WORK / 'mods' / 'scripts'
    outdir.mkdir(parents=True, exist_ok=True)
    for fname, targets in EDITS.items():
        chunks = []
        for full, scripts in targets:
            e = p.by_full(full)
            label = qb_label(e)
            base = qbtext.decompile_qb(Q.parse(e.data))
            new = drop_lock(base, scripts)
            chunks.append(''.join(difflib.unified_diff(base.splitlines(True), new.splitlines(True),
                                                       f'a/{label}.q', f'b/{label}.q')))
        head = (f'// p8patch demo mod ({fname}): remove the forced render_lock_framerate = 2\n'
                f'// generated by tools/qbc/make_demo_mods.py\n')
        (outdir / fname).write_text(head + ''.join(chunks), encoding='utf-8', newline='\n')
        print('wrote', outdir / fname)
    # example: the cutscene edit as a full-script replacement (.q) - not in mods/scripts, so not applied
    ex = WORK / 'mods' / 'examples'
    ex.mkdir(parents=True, exist_ok=True)
    e = p.by_full(0x7b9ec42b)
    q = Q.parse(e.data)
    sec = next(s for s in q.sections if s.type == Q.SCRIPT and qbtext.name_text(s.key) == 'CutsceneSetup')
    txt = drop_lock(qbtext.decompile_script(sec.key, sec.value), ['CutsceneSetup'])
    (ex / f'{qb_label(e)}.q').write_text(
        '// p8patch: target=7b9ec42b\n// example replacement mod: same effect as 10_cutscene_render_unlock.diff\n\n'
        + txt + '\n', encoding='utf-8', newline='\n')
    print('wrote', ex / f'{qb_label(e)}.q')


if __name__ == '__main__':
    main()
