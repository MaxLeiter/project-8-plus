#!/usr/bin/env python3
"""Refresh builder/p8ui/assets (fonts, icon font, licences) and builder/p8ui/icons.py from upstream releases.

Developer tool, not shipped. The assets are committed; the app never downloads anything. Run it only to bump a
font or the icon set:

    python packaging/make_ui_assets.py \
        --inter   <unpacked Inter-4.1.zip (rsms/inter release)> \
        --barlow  <folder with google/fonts ofl/barlowcondensed BarlowCondensed-*.ttf + OFL.txt> \
        --jbmono  <unpacked JetBrainsMono-2.304.zip> \
        --lucide  <folder with lucide-static's font/lucide.ttf, font/info.json and LICENSE>

Text fonts are subset with fontTools to Latin (Basic, Latin-1, Extended-A/B), general punctuation, arrows and
the few symbols the UI uses: about a quarter of the upstream size. None of the fonts declares a Reserved Font
Name, so a subset may keep its name (OFL 1.1 section 3). The icon font is copied whole (every Lucide icon is
available to every panel) and icons.py lists all of its names.
"""
import argparse
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
P8UI = os.path.join(os.path.dirname(HERE), "builder", "p8ui")
FONTS = os.path.join(P8UI, "assets", "fonts")
LICS = os.path.join(P8UI, "assets", "licenses")

UNICODES = ",".join([
    "U+0020-007E", "U+00A0-00FF", "U+0100-017F", "U+0180-024F",   # Latin
    "U+2000-206F",                                                 # general punctuation (dashes, quotes, ...)
    "U+20AC", "U+2122", "U+2190-21FF",                              # euro, TM, arrows
    "U+2212", "U+2215", "U+221E", "U+2248", "U+2260", "U+2264-2265",  # math bits
    "U+2318", "U+2325", "U+232B", "U+23CE", "U+2303", "U+21E7",     # key symbols
    "U+25A0-25FF", "U+2713", "U+2715", "U+2022", "U+00B7",          # shapes, check, cross, bullets
])


def subset(src, dst):
    from fontTools import subset as fts
    opts = fts.Options()
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.name_languages = ["*"]
    opts.notdef_outline = True
    opts.hinting = True
    font = fts.load_font(src, opts)
    sub = fts.Subsetter(opts)
    sub.populate(unicodes=fts.parse_unicodes(UNICODES))
    sub.subset(font)
    fts.save_font(font, dst, opts)
    print(f"  {os.path.basename(dst)}: {os.path.getsize(src) // 1024} KB -> {os.path.getsize(dst) // 1024} KB")


def find(root, name):
    for dp, _, fns in os.walk(root):
        if name in fns:
            return os.path.join(dp, name)
    sys.exit(f"make_ui_assets: {name} not found under {root}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--inter", required=True)
    ap.add_argument("--barlow", required=True)
    ap.add_argument("--jbmono", required=True)
    ap.add_argument("--lucide", required=True)
    a = ap.parse_args()
    os.makedirs(FONTS, exist_ok=True)
    os.makedirs(LICS, exist_ok=True)

    print("fonts")
    for w in ("Regular", "Medium", "SemiBold", "Bold"):
        subset(find(a.inter, f"Inter-{w}.ttf"), os.path.join(FONTS, f"Inter-{w}.ttf"))
    for w in ("SemiBold", "Bold", "ExtraBold"):
        subset(find(a.barlow, f"BarlowCondensed-{w}.ttf"), os.path.join(FONTS, f"BarlowCondensed-{w}.ttf"))
    for w in ("Regular", "Bold"):
        subset(find(a.jbmono, f"JetBrainsMono-{w}.ttf"), os.path.join(FONTS, f"JetBrainsMono-{w}.ttf"))
    shutil.copyfile(find(a.lucide, "lucide.ttf"), os.path.join(FONTS, "lucide.ttf"))

    print("licences")
    shutil.copyfile(find(a.inter, "LICENSE.txt"), os.path.join(LICS, "Inter-OFL.txt"))
    shutil.copyfile(find(a.barlow, "OFL.txt"), os.path.join(LICS, "BarlowCondensed-OFL.txt"))
    shutil.copyfile(find(a.jbmono, "OFL.txt"), os.path.join(LICS, "JetBrainsMono-OFL.txt"))
    shutil.copyfile(find(a.lucide, "LICENSE"), os.path.join(LICS, "Lucide-LICENSE.txt"))

    info = json.load(open(find(a.lucide, "info.json"), encoding="utf-8"))
    pkg = os.path.join(a.lucide, "package.json")
    ver = json.load(open(pkg, encoding="utf-8")).get("version", "?") if os.path.isfile(pkg) else "?"
    names = sorted(info)
    lines = [
        '"""Lucide icon codepoints (generated by packaging/make_ui_assets.py from lucide-static %s; do not edit).' % ver,
        "",
        "Lucide (ISC, https://lucide.dev): every name of the icon font in assets/fonts/lucide.ttf.",
        "Use: `from p8ui.icons import ICON; ICON['play']` or the attribute form `icons.PLAY` (dashes -> underscores).",
        'Browse names at https://lucide.dev/icons (offline: p8ui.gallery shows the ones the apps use)."""',
        "",
        "ICON = {",
    ]
    for n in names:
        cp = int(info[n]["encodedCode"].lstrip("\\"), 16)
        lines.append(f'    "{n}": "\\u{cp:04x}",')
    lines += ["}", "", "", "def __getattr__(name):",
              '    key = name.lower().replace("_", "-")',
              "    try:", "        return ICON[key]", "    except KeyError:",
              "        raise AttributeError(f\"no Lucide icon {key!r}\") from None", "",
              "", "RANGE = (%s, %s)  # codepoint range of the icon font" % (
                  hex(min(int(info[n]["encodedCode"].lstrip("\\"), 16) for n in names)),
                  hex(max(int(info[n]["encodedCode"].lstrip("\\"), 16) for n in names))), ""]
    with open(os.path.join(P8UI, "icons.py"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    with open(os.path.join(P8UI, "assets", "VERSIONS.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("Inter 4.1 (rsms/inter release zip), subset\n"
                 "Barlow Condensed (google/fonts ofl/barlowcondensed), subset\n"
                 "JetBrains Mono 2.304 (JetBrains/JetBrainsMono release zip), subset\n"
                 f"Lucide icon font, lucide-static {ver}, unmodified\n")
    print(f"icons.py: {len(names)} icons (lucide-static {ver})")


if __name__ == "__main__":
    raise SystemExit(main())
